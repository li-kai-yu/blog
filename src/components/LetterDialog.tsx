import { useEffect } from 'react'
import { Close } from './Icons'

type LetterDialogProps = {
  open: boolean
  onClose: () => void
}

export default function LetterDialog({ open, onClose }: LetterDialogProps) {
  useEffect(() => {
    if (!open) return

    const onKey = (event: KeyboardEvent) => {
      if (event.key === 'Escape') onClose()
    }

    const previousOverflow = document.body.style.overflow
    document.body.style.overflow = 'hidden'
    document.addEventListener('keydown', onKey)

    return () => {
      document.removeEventListener('keydown', onKey)
      document.body.style.overflow = previousOverflow
    }
  }, [open, onClose])

  if (!open) return null

  return (
    <div className="letter-overlay" role="presentation" onClick={onClose}>
      <article
        className="letter"
        role="dialog"
        aria-modal="true"
        aria-labelledby="letter-title"
        onClick={(event) => event.stopPropagation()}
      >
        <button type="button" className="letter__close" aria-label="关闭来信" onClick={onClose}>
          <Close size={18} />
        </button>

        <div className="letter__meta">
          <span>FROM ELIO</span>
          <span>大二上 · 2026.11</span>
        </div>

        <h2 id="letter-title">写给正在学计算机的你</h2>

        <div className="letter__body">
          <p>
            嘿，是我。大半夜点开的，就先把手机扣在桌上，听我唠几句。
          </p>
          <p>
            我知道你最近挺烦：简历投出去没动静，实习一个比一个难找，
            身边人动不动来一句「计算机不行了」。这不是错觉，寒冬是真的。
            我第一次在 BOSS 上投简历，头像换了、打招呼语改了三遍，
            挑了十几家公司一家家发，结果不是已读不回，就是未读石沉大海。
            等了两天，连一句「不合适」都没等到。
          </p>
          <p>
            后来我想明白：不是我不够努力，是我努力的方向市场不认。
            下面的话有点冲，你可能会不舒服，但没有一句是站着说话不腰疼——
            因为有些话，我也曾对自己说过。
          </p>

          <h3>说几句难听的，你爱听不听</h3>
          <p>
            大学课程给你的是张地图，不是饭碗。课上听懂、考试高分，
            和「能自己写个东西、能解释一次线上故障、能在面试里把方案讲明白」，
            是两码事。四年全交给课表，上课睡觉、期末突击、考完就忘，
            毕业时怪学校、怪行业——HR 不理你，真不冤。
          </p>
          <p>
            也别自欺欺人。收藏夹里躺着几百个 G 的视频，一个都没看完；
            简历写着「精通」，面试官多问一句就冒汗；项目跟着视频敲，换个需求就不会改。
            这不叫会，叫看过。更别把「在图书馆坐了一天」当努力，
            难的是关掉视频，自己从零写，报错自己查。
          </p>

          <h3>一门课真的需要一个学期吗</h3>
          <p>
            先说句公道话：很多老师讲得不错，这不是他们的问题。
            但你扪心自问，一门课真的需要一个学期吗？同样一本教材，
            自己找资料、看文档、跟着写代码，半个月就能学得挺扎实，甚至更深——
            因为每一处卡住的地方，你都得自己解决，解决一次就真记住了。
          </p>
          <p>
            一个学期十六周，每周两节课，扣掉走神、点名、玩手机，
            真正听进去的不到三十个小时。这些时间够你把一门语言学出样子，
            也够把一个小项目从零做到上线。课要去，学分要拿，
            但别把「老师讲得好」当成自己慢慢来的理由。
            大学最贵的不是学费，是时间。
          </p>

          <h3>醒醒，你连门都还没进</h3>
          <p>
            问 Git 是什么，有人反问「是 GitHub 吗」；clone、commit、push、branch
            一个没用过，代码只存在自己的 D 盘。能独立写出来的程序，
            想了半天说一个 for 循环从 1 加到 100。IDEA 不会建项目、
            不会建 package 和 class，打开现成项目满屏红线，第一反应是关掉重开。
            这些不是加分项，是及格线。
          </p>
          <p>
            还有人以为学 Java 就是把语法过一遍。语法只是入场券，
            后面站着 Maven、Spring Boot、MySQL、Redis、消息队列、Linux、JVM、
            并发和网络，一个都绕不开。「会四门语言」也多半是四门都只看了目录。
          </p>
          <p>
            八股背过，问深一层就卡，因为从没在代码里见过；AI 别人已经用来读源码、
            补测试，你生成一段看都不看就贴进去，跑不起来再骂 AI 不行。
            写了两道数学题发个朋友圈，晚上开黑到一两点——
            这不叫上大学，叫混日子，还是自己骗自己的那种。
          </p>
          <p>
            我说这些不是为了踩你，是见过太多人拖到大三下才开始慌，
            打开简历发现什么也写不出来。到那时候，是真的来不及补。
          </p>

          <h3>还有几句，说给装睡的人</h3>
          <p>
            前后端都分不清，就跟着别人买课、报班，喊「我要进大厂」。
            不少人把实习当兼职：只问一天多少钱，不问能接触什么项目、有没有人带。
            兼职是拿时间换钱，实习是拿时间换经验。
          </p>
          <p>
            还有一句更现实的：用人单位没有义务为我们的教育成本买单。
            学费是交给学校的，不是交给公司的。公司招人，是让你来解决问题、
            创造价值的，不是接着把大学没教完的课给你补上。
            愿意花时间带你，是运气；不带你，是本分。
          </p>
          <p>
            最无奈的是选择性耳聋。学长学姐说早点自学，你说知道；网上路线图铺得到处都是，
            你点头点得比谁都快，然后一转头继续刷短视频、开黑，说「明天开始」。
            你能骗过今天的自己，骗不过三年后投简历的自己。
          </p>

          <h3>网上那些建议，我帮你翻译一下</h3>
          <p>
            「尽早实习」是让企业看到你做过什么，不是绩点单；「做项目」不是抄教程，
            苍穹外卖、瑞吉、黑马点评面试官一天能看几十遍，你得敢换需求、加真实约束；
            刷题背八股是过筛子的工具，不是能力本身；学好英语，因为文档、报错、
            issue 大多是英文；拥抱 AI，不是把它当答案生成器，而是你得有判断它对不对的能力。
          </p>

          <h3>这些坑我自己也踩过</h3>
          <p>
            上面那些话，有一半是在骂以前的自己。我也有过只跟着教程走的日子，
            项目能跑，但教程一关，连个登录接口都得憋半天。
            后来我逼自己关掉教程重写、找真实场景用上、每做完一个项目写一篇复盘。
          </p>
          <p>
            我还回头补了网络、操作系统、数据库。小林coding 的图解系列帮了我大忙，
            但真正让我开窍的，是看完之后自己拿 curl、EXPLAIN、jstat 验证一遍。
            简历也改了十几版，从满篇「熟悉」「了解」，换成我做过什么、遇到什么问题、
            最后怎么解决。
          </p>

          <h3>最后再骂几句</h3>
          <p>
            别再问「现在开始还来得及吗」；别信「21 天精通」「三个月上岸大厂」；
            别把考研当避难所；别拿「双非」当挡箭牌。学校决定不了你三年里能写多少代码、
            能踩多少坑。还有简历，别包装，别造假——试用期被拆穿，
            比一开始被拒绝难看得多。
          </p>

          <h3>骂完了，说点能做的</h3>
          <p>
            先把一门语言学到能独立写东西，再挑个方向做个小项目，
            从设计、编码到部署完整走一遍。最笨但最稳的路线是：
            大一学语言、环境、Git、Linux；大二补数据结构和算法，做一个能上线的小项目，
            开始写博客；大三投实习、定方向；大四秋招和毕设一起推。
            别跳步，Java SE 没学完就去看 Spring Cloud，看完也只会复制配置。
          </p>
          <p>
            已经大三、大四了也别摆烂。做一个小闭环：一个能跑起来的项目，
            一份能讲清细节的简历，每天固定两小时补基础和投递。
            每天一点，比周末一口气学十二个小时管用。
          </p>
          <p>
            投简历已读不回，不代表你这个人不行，只代表你现在拿出来的东西还不够。
            难过一晚上可以，第二天把简历再改一版，把项目再补一块。
          </p>

          <p>
            寒冬不会因为你焦虑就结束，这个我保证不了。
            但你能让自己没那么容易被替代，这事自己说了算。
            等春天来的时候，希望你已经有自己的根了。
          </p>
          <p>
            如果只能记住一句话，那就记住：大学最值钱的不是课堂，
            是没人管你的时候，你在干什么。别把大学过成高四，
            也别把迷茫当成不动的理由。
          </p>
          <p>
            这学期还剩两个月，别急着立「下学期一定」的 flag，就从今天开始：
            把开发环境配好，把一个小项目跑起来，把简历写出第一版。
            行了，去写代码吧，写完记得睡觉。
          </p>
        </div>

        <div className="letter__sign">
          <span>Elio</span>
          <em>于洛阳 · 河南科技大学</em>
        </div>
      </article>
    </div>
  )
}
